-- -----------------------------------------------------------------------------
-- 4. Service-role grants for system_logs (service_role ONLY)
-- -----------------------------------------------------------------------------
-- 0001 Section D set ALTER DEFAULT PRIVILEGES that may auto-grant full DML on
-- new tables to service_role. For the audit trail we keep INSERT + SELECT and
-- explicitly REVOKE UPDATE / DELETE / TRUNCATE so audit rows stay immutable
-- even with the service-role key. anon and authenticated receive nothing.
GRANT SELECT, INSERT ON TABLE public.system_logs TO service_role;
REVOKE UPDATE, DELETE, TRUNCATE ON TABLE public.system_logs FROM service_role;
GRANT USAGE, SELECT ON SEQUENCE public.system_logs_id_seq TO service_role;

REVOKE ALL ON TABLE public.system_logs FROM anon, authenticated;

