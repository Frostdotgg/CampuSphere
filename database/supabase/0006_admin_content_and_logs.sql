-- Apply order
--   This file is the sixth Supabase migration. Apply in order:
--     1. database/supabase/0001_initial_schema.sql
--     2. database/supabase/0002_seed_data.sql
--     3. database/supabase/0003_auth_profile_functions.sql
--     4. database/supabase/0004_building_backfill.sql
--     5. database/supabase/0005_building_write_functions.sql
--     6. database/supabase/0006_admin_content_and_logs.sql            <-- this file
--   Re-applying is safe: the table uses CREATE TABLE / INDEX IF NOT EXISTS,
--   the FAQ seed upserts by exact question, the settings seed upserts
--   ON CONFLICT (setting_key), and the grants / revokes are repeatable.
--
-- Privacy and immutability (audit)
--   system_logs stores WHAT happened plus a safe message ONLY. It NEVER stores
--   IP addresses, passwords, request bodies, tokens, cookies, session IDs,
--   OAuth subjects, secrets, or stack traces. There is no updated_at column
--   and no audit update / delete function: rows are immutable through the
--   application. service_role is granted SELECT + INSERT only, and
--   UPDATE / DELETE / TRUNCATE are revoked, so the audit trail cannot be
--   rewritten even with the service-role key.
--
-- Access decision
--   Every grant below is scoped to service_role ONLY -- never anon, never
--   authenticated. The browser, EJS, and public JS never see the service-role
--   key (see 0001 Section D and the config/supabase.js header).
-- =============================================================================


-- -----------------------------------------------------------------------------
-- 1. system_logs -- Postgres equivalent of the database/schema.sql table
-- -----------------------------------------------------------------------------
--   actor_user_id is bigint to match users.id (Supabase identity); the MySQL
--   table uses INT to match its INT users.id. ON DELETE SET NULL keeps audit
--   history when a user row is later removed.
CREATE TABLE IF NOT EXISTS system_logs (
    id              bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type      varchar(50)   NOT NULL,
    action          varchar(100)  NOT NULL,
    outcome         varchar(20)   NOT NULL,
    actor_user_id   bigint
        REFERENCES users(id) ON DELETE SET NULL,
    attempted_email varchar(100),
    actor_role      varchar(30),
    target_type     varchar(50),
    target_id       varchar(100),
    message         varchar(500)  NOT NULL,
    created_at      timestamptz   NOT NULL DEFAULT now()
);

-- Newest-first listing.
CREATE INDEX IF NOT EXISTS system_logs_created_at_idx
    ON system_logs (created_at DESC);

-- Bounded event_type + outcome filtering, newest-first within a filter.
CREATE INDEX IF NOT EXISTS system_logs_event_outcome_created_idx
    ON system_logs (event_type, outcome, created_at DESC);


